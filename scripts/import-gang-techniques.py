"""Build the offline gang catalogue using Threat Vision's active `uses` walk.

Usage: python scripts/import-gang-techniques.py <enterprise-attack.json>
The input is the Enterprise ATT&CK 20.1 STIX bundle used for this snapshot.
"""
import hashlib
import json
from pathlib import Path
import sys

REFERENCE = "8f93e855ca7a9427935016c7efae6f7bc96133aa"
ROOTS = {
    "lockbit": ["S1199", "S1202"],
    "conti": ["S0575"],
    "blackcat": ["S1068"],
    "hive": [],  # No Hive software/group entry in this Enterprise snapshot.
    "revil": ["S0496"],
}


def build(raw):
    objects = json.loads(raw)["objects"]
    if not any(o["type"] == "x-mitre-collection" and o.get("name") == "Enterprise ATT&CK" and o.get("x_mitre_version") == "20.1" for o in objects):
        raise ValueError("Expected the pinned Enterprise ATT&CK 20.1 bundle")
    active = {o["id"]: o for o in objects if not o.get("revoked") and not o.get("x_mitre_deprecated")}
    def attack_id(o):
        return next((r["external_id"] for r in o.get("external_references", [])
                     if r.get("source_name") == "mitre-attack" and r.get("external_id")), None)
    by_attack = {attack_id(o): o for o in active.values() if attack_id(o)}
    relations = [o for o in active.values() if o["type"] == "relationship"
                 and o.get("source_ref") in active and o.get("target_ref") in active]
    def related(entity, relation, types):
        return [r for r in relations if r["source_ref"] == entity and r["relationship_type"] == relation
                and active[r["target_ref"]]["type"] in types]
    gangs = {}
    for gang, ids in ROOTS.items():
        techniques = {}
        def walk(root, entity, via):
            for r in related(entity, "uses", {"attack-pattern"}):
                t = active[r["target_ref"]]
                tid = attack_id(t)
                entry = techniques.setdefault(tid, {"name": t["name"], "platforms": t.get("x_mitre_platforms", []), "evidence": []})
                entry["evidence"].append({"root": attack_id(root), "source": attack_id(active[entity]),
                    "via": via, "relationshipId": r["id"], "references": r.get("external_references", [])})
            for r in related(entity, "uses", {"malware", "tool"}):
                for use in related(r["target_ref"], "uses", {"attack-pattern"}):
                    t = active[use["target_ref"]]
                    entry = techniques.setdefault(attack_id(t), {"name": t["name"], "platforms": t.get("x_mitre_platforms", []), "evidence": []})
                    entry["evidence"].append({"root": attack_id(root), "source": attack_id(active[r["target_ref"]]),
                        "via": via + [attack_id(active[r["target_ref"]])], "relationshipId": use["id"], "references": use.get("external_references", [])})
        for aid in ids:
            root = by_attack[aid]  # Fail rather than silently accepting a missing selection.
            walk(root, root["id"], [])
            if root["type"] == "intrusion-set":
                for r in relations:
                    if r["relationship_type"] == "attributed-to" and r["target_ref"] == root["id"] and active[r["source_ref"]]["type"] == "campaign":
                        walk(root, r["source_ref"], [attack_id(active[r["source_ref"]])])
        gangs[gang] = {"roots": ids, "techniques": dict(sorted(techniques.items()))}
    return {"schemaVersion": 1, "sources": {
        "threatVision": f"https://github.com/kaligraeme/mitre-threat-vision-ncs/blob/{REFERENCE}/js/sim-engine.js",
        "attackBundle": "https://raw.githubusercontent.com/mitre-attack/attack-stix-data/master/enterprise-attack/enterprise-attack-20.1.json",
        "attackVersion": "20.1", "sha256": hashlib.sha256(raw).hexdigest(),
        "selection": {"viaSoftware": True, "viaCampaigns": True, "platforms": []},
        "reviewed": "2026-11-20"}, "gangs": gangs}


if __name__ == "__main__":
    catalogue = build(Path(sys.argv[1]).read_bytes())
    target = Path(__file__).resolve().parents[1] / "js" / "gang-techniques.js"
    target.write_text("// Generated by scripts/import-gang-techniques.py; MITRE ATT&CK data: https://attack.mitre.org/resources/legal-and-branding/\n"
        "(function(root,factory){if(typeof module==='object'&&module.exports)module.exports=factory();else root.GangTechniques=factory();})"
        "(typeof self!=='undefined'?self:this,function(){return " + json.dumps(catalogue, indent=2, ensure_ascii=True) + ";});\n", encoding="utf-8")
    print(f"Wrote {target}: " + str({g: len(p['techniques']) for g, p in catalogue['gangs'].items()}))
